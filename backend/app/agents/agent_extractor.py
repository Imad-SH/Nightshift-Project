class Observable(BaseModel):
    """
    Represents a single technical artifact with semantic metadata.
    """
    value: str = Field(description="The actual string extracted (e.g., '1248', '0x800702E4').")
    type: str = Field(description="Detailed technical type (e.g., 'PID', 'HRESULT', 'CLSID', 'Binary Path', 'User').")
    label: str = Field(description="Friendly name/category for the artifact.")
    context: Optional[str] = Field(None, description="Optional hex or human-readable context (e.g. 'Elevation Required').")

class UniversalExtraction(BaseModel):
    """
    Structured schema for semantic extraction of security observables.
    """
    identities: List[Observable] = Field(default_factory=list, description="Users, emails, account IDs, or unique identifiers.")
    network: List[Observable] = Field(default_factory=list, description="IP addresses, domains, URLs, user-agents, or network indicators.")
    system: List[Observable] = Field(default_factory=list, description="Command lines, registry keys, service names, process paths, or OS indicators.")
    files: List[Observable] = Field(default_factory=list, description="File names, paths, or hashes.")
    log_source: str = Field(default="Unknown", description="The exact system, software, or service that generated the log.")
    summary: str = Field(default="No summary available.", description="A short 1-sentence tactical summary.")
    status: str = Field(default="Complete", description="Status of the extraction (Complete or Failed)")

    def dict(self, **kwargs):
        # Make log_source more accurate and fallback gracefully
        d = super().dict(**kwargs)
        source = d.get('log_source', '')
        if not source or source.lower() in ["security logs", "unknown", "wazuh alert data", "wazuh"]:
            d['log_source'] = "Generic Security Log"
        return d

class IocExtractor:
    """
    Agent 1: IoC Extractor
    Role: Semantic extraction of technical observables using LLM.
    Ref: SOC Cognitif V2.1 Architecture
    """

    def __init__(self):
        # LLM will be initialized lazily to prevent startup crashes if API key is missing
        self._llm = None
        self.parser = PydanticOutputParser(pydantic_object=UniversalExtraction)

    def _get_llm(self):
        """Configure the LLM client properly matching Agent 3 stability"""
        if not self._llm:
            from app.core.config import settings
            
            if settings.ai_architecture == "LOCAL":
                model = settings.local_agent1_model or "llama3"
                base_url = settings.local_base_url
                api_key = "ollama" # Placeholder for local
            else:
                model = settings.agent1_model or settings.ai_extractor_model or settings.nebius_extractor_model
                base_url = settings.nebius_base_url or "https://api.tokenfactory.nebius.com/v1/"
                api_key = settings.nebius_api_key
            
            self._llm = ChatOpenAI(
                model_name=model,
                openai_api_key=api_key,
                openai_api_base=base_url,
                temperature=0.1,
                max_tokens=4096,
                timeout=60,
                model_kwargs={"max_completion_tokens": None} if "o1" not in model.lower() else {}
            )
        return self._llm

    def _clean_deepseek_thought(self, content: str) -> str:
        """
        Removes the <think>...</think> block generated by DeepSeek R1 models.
        Also attempts to extract just the JSON part if the model chats around it.
        """
        # 1. Strip thought block
        cleaned = re.sub(r'<think>.*?</think>', '', content, flags=re.DOTALL).strip()
        
        # 2. Extract JSON markdown block if present
        json_match = re.search(r'```json\s*(\{.*?\})\s*```', cleaned, flags=re.DOTALL)
        if json_match:
            return json_match.group(1)
            
        # 3. Fallback: try to find start/end of JSON
        start = cleaned.find('{')
        end = cleaned.rfind('}')
        if start != -1 and end != -1:
            return cleaned[start:end+1]
            
        return cleaned


    async def run(self, alert_id: str, raw_data: dict):
        """
        Executes the AI-based extraction phase.
        """
        # Phase 1: Ingestion Ack
        try:
            # Dynamic import for Socket.IO when run as a module
            try:
                from app.core.socket import sio
            except ImportError:
                sio = None

            if sio:
                await sio.emit('agent_update', {
                    "alert_id": alert_id,
                    "node": "listener",
                    "log": "[INIT] Cognitive Pipeline Triggered."
                })
            
            await asyncio.sleep(0.1)

            # Phase 2: Active Semantic Extraction
            if sio:
                await sio.emit('agent_update', {
                    "alert_id": alert_id,
                    "node": "agent_screener",
                    "log": "🧠 AI Initializing Semantic Extraction..."
                })
            print(f"DEBUG [Agent 1] Starting extraction for alert {alert_id}")

            # 1. Normalization Utility
            def normalize_dict(val):
                """Recursively parse JSON strings within a structure."""
                if isinstance(val, str) and (val.startswith('{') or val.startswith('[')):
                    try:
                        loaded = json.loads(val)
                        return normalize_dict(loaded)
                    except: return val
                if isinstance(val, dict):
                    return {k: normalize_dict(v) for k, v in val.items()}
                if isinstance(val, list):
                    return [normalize_dict(v) for v in val]
                return val

            def safe_get(obj, keys, default=None):
                """Safely traverse nested dictionary keys even if intermediate fields are strings."""
                curr = obj
                for k in keys:
                    if isinstance(curr, dict):
                        curr = curr.get(k, default)
                    else:
                        return default
                return curr if curr is not None else default

            # 2. Bulletproof Normalization
            norm_data = normalize_dict(raw_data)
            if not isinstance(norm_data, dict):
                norm_data = {}

            # 3. AGGRESSIVE CLEANING STRATEGY
            # We must prevent "hallucination loops" where Agent 1 extracts CTI links 
            # (URLScan, VT, etc) from previous Agent 2 investigations during a re-scan.
            
            def scrub_ai_data(obj):
                """Recursively remove any AI-generated or CTI-related keys from the context."""
                if not isinstance(obj, dict): return obj
                blacklisted_keys = {
                    'ai_analysis_results', 'results', 'ai_status', 'verdict', 
                    'graph_layout', 'rawData', 'external_intel', 'sources_queried', 
                    'critical_tags', 'analysis_reasoning'
                }
                clean_obj = {}
                for k, v in obj.items():
                    if k in blacklisted_keys: continue
                    # Also strip strings that look like previous AI outputs/links if they appear in values
                    if isinstance(v, str) and any(x in v for x in ['urlscan.io', 'virustotal.com', 'hybrid-analysis.com']):
                        # Only keep it if it looks like a legitimate vendor/msrc link (exception for CVEs)
                        if 'msrc.microsoft.com' not in v:
                            continue 
                    
                    if isinstance(v, dict):
                        clean_obj[k] = scrub_ai_data(v)
                    elif isinstance(v, list):
                        clean_obj[k] = [scrub_ai_data(x) if isinstance(x, dict) else x for x in v]
                    else:
                        clean_obj[k] = v
                return clean_obj

            # Apply to the raw data before un-nesting
            norm_data = scrub_ai_data(norm_data)
            
            # Using safe_get to avoid ANY 'str' object has no attribute 'get' errors
            forensic_context = norm_data if 'raw_data' not in norm_data else norm_data['raw_data']
            if not isinstance(forensic_context, dict): forensic_context = {}
            
            # Final cleaning of forensic_context itself
            forensic_context = scrub_ai_data(forensic_context)
            
            synthetic_context = {
                "alert_id": alert_id,
                "wazuh_rule_id": (safe_get(forensic_context, ['rule', 'id']) or
                                 safe_get(norm_data, ['rule', 'id']) or
                                 safe_get(norm_data, ['rule_id']) or '0000'),
                "alert_title": (safe_get(forensic_context, ['rule', 'description']) or
                                safe_get(norm_data, ['title']) or 'Unknown Alert'),
                "agent_name": (safe_get(forensic_context, ['agent', 'name']) or
                               safe_get(norm_data, ['source']) or 'Unknown Agent'),
                # Un-nesting Vital Fields
                "user": (safe_get(forensic_context, ['data', 'user']) or 
                         safe_get(forensic_context, ['data', 'targetUserName']) or 
                         safe_get(forensic_context, ['data', 'win', 'eventdata', 'targetUserName']) or 
                         safe_get(forensic_context, ['data', 'win', 'eventdata', 'subjectUserName']) or
                         safe_get(forensic_context, ['data', 'dstuser'])),
                "srcip": (safe_get(forensic_context, ['data', 'srcip']) or 
                          safe_get(forensic_context, ['data', 'ipAddress']) or 
                          safe_get(forensic_context, ['data', 'win', 'eventdata', 'ipAddress'])),
                "command": (safe_get(forensic_context, ['data', 'command']) or 
                            safe_get(forensic_context, ['data', 'commandLine']) or 
                            safe_get(forensic_context, ['data', 'win', 'eventdata', 'commandLine'])),
                "file_path": (safe_get(forensic_context, ['data', 'file']) or 
                              safe_get(forensic_context, ['data', 'image']) or 
                              safe_get(forensic_context, ['data', 'win', 'eventdata', 'image'])),
                # Adding Log Source Context
                "log_source_hint": (safe_get(forensic_context, ['decoder', 'name']) or 
                                    safe_get(forensic_context, ['location']) or 
                                    safe_get(forensic_context, ['rule', 'groups']) or 
                                    'Unknown Security Log'),
                # Full visibility: Sending the entire raw log for exhaustive analysis
                "raw_log_blob": str(forensic_context)
            }

            print(f"DEBUG [Agent 1] Alert ID: {alert_id}")
            print(f"DEBUG [Agent 1] Synthetic Indicators: User={synthetic_context.get('user')}, IP={synthetic_context.get('srcip')}")

            # Create the high-fidelity forensic prompt
            from app.core.config import settings
            mission_params = settings.agent1_prompt if hasattr(settings, 'agent1_prompt') and settings.agent1_prompt else "Extract all relevant security observables while maintaining perfect JSON format."
            
            base_prompt = """
### ROLE
You are an Elite SOC Forensic Analyst. Your task is to extract technical indicators (IOCs) from the provided security log.

### SECURITY LOG DATA
{{SECURITY_LOG_DATA}}

### INSTRUCTIONS
1. Analyze the 'raw_log_blob' and synthetic fields.
2. Identify all technical artifacts (observables).
3. ### MANDATORY SCHEMA RULE:
   - EVERY item in 'identities', 'network', 'system', and 'files' MUST be an object following the 'Observable' schema.
   - NEVER return a raw string in these lists.
   - For each item, determine its most specific technical label (e.g. 'Process ID', 'CLSID', 'HRESULT Error', 'Account SID', 'Binary Path', 'WMI Class').
   - If a value is a number, identify what it represents in the context of the log (e.g. 'Process ID').

4. Be EXHAUSTIVE but ACCURATE. Do not invent data.

### SPECIAL CONSTRAINTS (AGENT 1)
- NEVER extract links to CTI tools (e.g., urlscan.io, virustotal.com, hybrid-analysis.com).
- IGNORE any previous AI analysis results if they accidentally appear in the log.
- Focus ONLY on the original artifacts from the compromised/monitored system.

### MISSION PARAMETERS (SPECIFIC USER INSTRUCTIONS)
{{MISSION_PARAMETERS}}

{{FORMAT_INSTRUCTIONS}}

IMPORTANT: 
- Extract the username into the 'identities' list.
- Provide a clear 'summary' of the event.
- Return ONLY the JSON object.
"""
            # Safe injection to prevent curly-brace injection errors
            prompt = base_prompt.replace("{{SECURITY_LOG_DATA}}", json.dumps(synthetic_context, indent=2))
            prompt = prompt.replace("{{MISSION_PARAMETERS}}", mission_params)
            prompt = prompt.replace("{{FORMAT_INSTRUCTIONS}}", self.parser.get_format_instructions())
            
            llm = self._get_llm()
            active_model = llm.model_name if hasattr(llm, 'model_name') else "DeepSeek-V4.1-Flash"

            if sio:
                await sio.emit('agent_update', {
                    "alert_id": alert_id,
                    "node": "agent_screener",
                    "model": active_model,
                    "log": "⏳ [AI] Generating extraction map (Thinking...)"
                })
            
            response = await llm.ainvoke(prompt)
            print(f"DEBUG [Agent 1] LLM Response received for alert {alert_id}.")
            raw_content = response.content if hasattr(response, 'content') else str(response)
            
            # ROBUST JSON EXTRACTION
            try:
                clean_json = self._clean_deepseek_thought(raw_content)
                extracted_dict = json.loads(clean_json)
                extracted = UniversalExtraction(**extracted_dict)
            except Exception as parse_error:
                from app.agents.llm_errors import finish_details
                reason = f"LLM Output Parsing Failed: {parse_error}"
                details = finish_details(response)
                if details:
                    reason += f". {details}"
                print(f"⚠️ [Agent 1] {reason} ({len(raw_content or '')} chars received) for {alert_id}")
                extracted = UniversalExtraction(status="Failed", summary=reason)

            # Log results to the UI
            if sio:
                await sio.emit('agent_update', {
                    "alert_id": alert_id,
                    "node": "agent_screener",
                    "model": active_model,
                    "log": f"[AI EXTRACTOR] {extracted.summary}"
                })

            res = extracted.dict()
            
            # --- POST-EXTRACTION SAFETY WRAPPER ---
            # Ensures that even if the LLM leaked raw strings, they are wrapped for the UI
            def wrap_legacy_items(items, category):
                wrapped = []
                for item in items:
                    if isinstance(item, dict):
                        wrapped.append(item)
                    else:
                        # Fallback labeling logic moved to backend to reduce frontend complexity
                        val = str(item)
                        label = "Unknown Artifact"
                        if category == 'system':
                            if val.isdigit() and len(val) < 6: label = "Process ID"
                            elif '{' in val and '}' in val: label = "CLSID / GUID"
                            elif '\\' in val or '/' in val: label = "System Path"
                        elif category == 'identities': label = "Identity / SID"
                        elif category == 'network': label = "Network Indicator"
                        
                        wrapped.append({
                            "value": val,
                            "type": "LEGACY_WRAP",
                            "label": label,
                            "context": "Auto-labeled"
                        })
                return wrapped

            for cat in ['identities', 'network', 'system', 'files']:
                if cat in res:
                    res[cat] = wrap_legacy_items(res[cat], cat)

            res['model'] = active_model
            return res

        except Exception as e:
            import traceback
            tb = traceback.format_exc()
            error_log = f"❌ [AI Extraction Error]: {str(e)}\n{tb}"
            print(error_log)
            # Notify UI
            if sio:
                try: await sio.emit('agent_update', {"alert_id": alert_id, "node": "agent_screener", "model": active_model if 'active_model' in locals() else "System Fallback", "log": f"Extraction failed: {str(e)}"})
                except: pass
            
            return {
                "identities": [], "network": [], "system": [], "files": [],
                "log_source": "Unknown",
                "summary": f"Extraction failed: {str(e)}",
                "status": "Failed",
                "model": "System Fallback"
            }

ioc_extractor = IocExtractor()

