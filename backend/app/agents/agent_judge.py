# --- OUTPUT SCHEMA ---
class AgentVerdict(BaseModel):
    verdict: str = Field(description="The final verdict: 'Suspicious', 'Malicious', or 'False Positive'")
    confidence_score: int = Field(description="Confidence score between 0 and 100")
    severity: str = Field(description="Severity level: 'Low', 'Medium', 'High', 'Critical'")
    analysis_reasoning: str = Field(description="Concise executive summary explaining the decision")
    key_evidence: List[str] = Field(description="List of specific artifacts or indicators that drove the decision")
    mitigation_steps: List[str] = Field(description="List of recommended actionable mitigation steps")
    mitre_tactics: List[str] = Field(description="List of relevant MITRE ATT&CK tactics found")

class AgentJudge:
    """
    Agent 3: The Judge (Final Decision Maker)
    Role: Synthesizes extraction, CTI pipeline results, and raw logs to issue a final verdict using DeepSeek R1.
    """

    def __init__(self):
        # Lazy initialization of LLM
        self.llm = None
        self.parser = PydanticOutputParser(pydantic_object=AgentVerdict)

    def _get_llm(self):
        if not self.llm:
            from app.core.config import settings
            
            if settings.ai_architecture == "LOCAL":
                model = settings.local_agent3_model or "llama3"
                base_url = settings.local_base_url
                api_key = "ollama" # Placeholder for local
            else:
                model = settings.agent3_model or settings.ai_judge_model or settings.nebius_judge_model or "deepseek-ai/DeepSeek-V4-Pro"
                base_url = settings.nebius_base_url or "https://api.tokenfactory.nebius.com/v1/"
                api_key = settings.nebius_api_key
            
            self.llm = ChatOpenAI(
                model_name=model,
                openai_api_key=api_key,
                openai_api_base=base_url,
                temperature=0.1,
                max_tokens=4096,
                timeout=110,
                model_kwargs={"max_completion_tokens": None} if "o1" not in model.lower() else {}
            )
        return self.llm

    def _clean_deepseek_thought(self, content: str) -> str:
        """
        Removes the <think>...</think> block generated by DeepSeek R1 models.
        Also attempts to extract just the JSON part if the model chats around it.
        """
        # 1. Strip thought block
        cleaned = re.sub(r'<think>.*?</think>', '', content, flags=re.DOTALL).strip()
        
        # 2. Extract JSON markdown block if present
        json_match = re.search(r'```json\s*(\{.*?\})\s*```', cleaned, flags=re.DOTALL)
        if json_match:
            return json_match.group(1)
            
        # 3. Fallback: try to find start/end of JSON
        start = cleaned.find('{')
        end = cleaned.rfind('}')
        if start != -1 and end != -1:
            return cleaned[start:end+1]
            
        return cleaned

    async def _emit_status(self, alert_id: str, status: str, log: str = ""):
        try:
            from app.core.socket import sio
            payload = {
                "alert_id": alert_id, 
                "node": "agent_judge", 
                "status": status
            }
            if log:
                payload["log"] = log
            await sio.emit('agent_update', payload)
        except:
            pass

    async def run(self, alert_id: str, extraction_data: Dict[str, Any], investigation_data: Dict[str, Any], raw_log: Dict[str, Any]) -> Dict[str, Any]:
        """
        Executes the judgment logic.
        """
        try:
            llm = self._get_llm()
            active_model = llm.model_name if hasattr(llm, 'model_name') else "DeepSeek-V4-Pro"
            
            # 🔥 CRITICAL: Combined broadcast to sync Model + Status + Log immediately
            from app.core.socket import sio
            if sio:
                await sio.emit('agent_update', {
                    "alert_id": alert_id,
                    "node": "agent_judge",
                    "status": "active",
                    "model": active_model,
                    "log": "🧠 [AI] Deliberating on forensic evidence... (Deep Reasoning)"
                })

            # 1. Context Preparation — reads from the new flat payload
            burst_global = investigation_data.get("burst_global", 0)
            burst_source = investigation_data.get("burst_source", 0)
            is_burst = investigation_data.get("is_burst", False)
            distinct_rules = investigation_data.get("cooc_distinct", 0)
            is_suspicious_cooc = investigation_data.get("is_suspicious_cooc", False)
            is_unusual_timing = investigation_data.get("is_unusual_timing", False)
            current_hour = investigation_data.get("current_hour", 0)
            hour_pct = investigation_data.get("hour_pct", 0.0)

            # Helper to safely extract list from external_intel
            external_intel = investigation_data.get("external_intel", [])

            # 2. Prompt Construction
            from app.core.config import settings
            mission_params = settings.agent3_prompt if hasattr(settings, 'agent3_prompt') and settings.agent3_prompt else "Synthesize all evidence to provide a definitive security verdict. Focus on actual technical risk."

            import textwrap
            base_template = textwrap.dedent("""
                ### MISSION OBJECTIVE
                You are the Final Verdict Judge in an Advanced SOC environment. Issuing a definitive verdict.
                State technical context clearly. Avoid generic placeholders.

                ### INPUT DATA:
                1. Raw Log: _RAW_LOG_
                2. Extracted Observables: _EXTRACTION_DATA_
                3. Investigation Results (CTI): _EXTERNAL_INTEL_
                4. Behavioral Context:
                   - This rule has triggered _BURST_GLOBAL_ times globally in the last 15 minutes (_BURST_SOURCE_ from this specific host).
                   - This specific host has triggered _DISTINCT_RULES_ different security rules in the last 1 hour.
                   - Historically, _HOUR_PCT_% of activity for this rule occurs during this hour window (Hour _CURRENT_HOUR_).

                ### DECISION RULES:
                1. CTI Priority: If ANY external tool (VirusTotal, AbuseIPDB, ThreatFox, AlienVault) reports Malicious or Risk Score >70, lean Malicious.
                2. Verified Noise Exception: If GreyNoise identifies a Verified Business Service or Reasonably Ignore, lean False Positive even with low-confidence detections.
                3. Behavioral Context: Consider the frequency of rule triggers, source-level correlation, and timing history to determine if the activity aligns with normal baseline behavior or represents an anomaly.
                4. Obfuscation: If CTI is Safe but Raw Log contains Base64, PowerShell download strings, or encoded commands, lean Suspicious.
                5. Safety: If insufficient evidence exists, default to Suspicious (Manual Review Required).

                ### MISSION PARAMETERS (SPECIFIC USER OVERRIDE):
                _MISSION_PARAMETERS_

                ### OUTPUT FORMAT:
                Return ONLY a valid JSON object matching this schema. NO PREAMBLE. NO EXPLANATION AFTER.
                {
                    "verdict": "Suspicious | Malicious | False Positive",
                    "confidence_score": <int 0-100>,
                    "severity": "Low | Medium | High | Critical",
                    "analysis_reasoning": "<Professional technical summary>",
                    "key_evidence": ["<evidence_1>", "<evidence_2>"],
                    "mitigation_steps": ["<step_1>", "<step_2>"],
                    "mitre_tactics": ["<tactic_1>"]
                }

                FINAL INSTRUCTION: Based on the MISSION PARAMETERS above, issue your final response in valid JSON.
            """).strip()
            formatted_prompt = base_template.replace("_RAW_LOG_", str(raw_log))
            formatted_prompt = formatted_prompt.replace("_EXTRACTION_DATA_", json.dumps(extraction_data, default=str))
            formatted_prompt = formatted_prompt.replace("_EXTERNAL_INTEL_", json.dumps(external_intel, default=str))
            formatted_prompt = formatted_prompt.replace("_BURST_GLOBAL_", str(burst_global))
            formatted_prompt = formatted_prompt.replace("_BURST_SOURCE_", str(burst_source))
            formatted_prompt = formatted_prompt.replace("_IS_BURST_", str(is_burst))
            formatted_prompt = formatted_prompt.replace("_DISTINCT_RULES_", str(distinct_rules))
            formatted_prompt = formatted_prompt.replace("_IS_SUSPICIOUS_COOC_", str(is_suspicious_cooc))
            formatted_prompt = formatted_prompt.replace("_CURRENT_HOUR_", str(current_hour))
            formatted_prompt = formatted_prompt.replace("_HOUR_PCT_", str(hour_pct))
            formatted_prompt = formatted_prompt.replace("_IS_UNUSUAL_TIMING_", str(is_unusual_timing))
            formatted_prompt = formatted_prompt.replace("_MISSION_PARAMETERS_", mission_params)

            # 3. LLM Execution
            response = await llm.ainvoke(formatted_prompt)
            clean_content = self._clean_deepseek_thought(response.content)

            # 4. Parsing
            try:
                verdict_data = self.parser.parse(clean_content)
                result = verdict_data.dict()
                result['model'] = active_model
            except Exception as e:
                from app.agents.llm_errors import finish_details
                print(f"[Judge] Parsing Error: {e}. Raw content: {clean_content}")
                details = finish_details(response)
                result = self._get_fail_safe_verdict(f"JSON Parsing Failed - manual review needed. Error: {str(e)}" + (f". {details}" if details else ""))
                result['model'] = active_model

            await self._emit_status(alert_id, "Complete", f"[Judge] Verdict: {result.get('verdict')} ({result.get('confidence_score')}%)")
            return result

        except Exception as e:
            error_msg = f"[Judge Error]: {str(e)}"
            print(error_msg)
            await self._emit_status(alert_id, "error", error_msg)
            return self._get_fail_safe_verdict(str(e))

    def _get_fail_safe_verdict(self, reason: str) -> Dict[str, Any]:
        """Returns a safe default verdict in case of failure."""
        return {
            "verdict": "Error",
            "confidence_score": 0,
            "severity": "Unknown",
            "analysis_reasoning": f"Automated analysis failed. Manual review required. Reason: {reason}",
            "key_evidence": ["System Error"],
            "mitigation_steps": ["Manual Investigation"],
            "mitre_tactics": [],
            "failed": True
        }

